"""Measure alpha gutters and feet for runtime crops; never modifies source images."""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
result={}
for name in ['brute','lizard','wraith','knight','frost','spider','demon']:
    im=Image.open(root/'assets'/f'{name}.png');a=im.getchannel('A');w,h=im.size
    # Search near cell boundaries for the cleanest transparent separator.
    xs=[0]+[min(range(round(w*c/6)-15,round(w*c/6)+16),key=lambda x:(sum(v>100 for v in a.crop((x,0,x+1,h)).tobytes()),abs(x-w*c/6))) for c in range(1,6)]+[w]
    frames=[]
    for col in range(6):
        ys=[0]+[min(range(round(h*r/5)-25,round(h*r/5)+26),key=lambda y:(sum(v>100 for v in a.crop((xs[col],y,xs[col+1],y+1)).tobytes()),abs(y-h*r/5))) for r in range(1,5)]+[h]
        for row in range(5):
            sx,sy=xs[col],ys[row];sw,sh=xs[col+1]-sx,ys[row+1]-sy
            box=a.crop((sx,sy,sx+sw,sy+sh)).point(lambda v:255 if v>100 else 0).getbbox()
            assert box, (name,row,col)
            frames.append({'row':row,'column':col,'sx':sx,'sy':sy,'sw':sw,'sh':sh,'ground':sy+box[3]})
    result[name]={'width':w,'height':h,'frames':sorted(frames,key=lambda f:f['row']*6+f['column'])}
(root/'enemy-atlas.mjs').write_text('// Generated by tools/measure-enemies.py; source PNGs remain unchanged.\nexport const ENEMY_ATLAS = '+json.dumps(result,separators=(',',':'))+';\n')
